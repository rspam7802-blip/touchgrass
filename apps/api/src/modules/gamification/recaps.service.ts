import { Inject, Injectable, Logger } from '@nestjs/common';
import {
  LocalizedText,
  previousRecapKey,
  type Recap,
  type RecapPeriod,
  type RecapStats,
  recapWindow,
} from '@touchgrass/shared';
import { and, desc, eq, gte, lt, sql } from 'drizzle-orm';
import { uuidv7 } from 'uuidv7';
import { AppError } from '../../common/errors/app-error.js';
import { DB, type Database, type Tx } from '../../infra/database/database.module.js';
import { gamificationFacts, recaps } from '../../infra/database/schema/index.js';
import { OutboxService } from '../../infra/outbox/outbox.service.js';
import { CitiesService } from '../cities/cities.service.js';
import { EventSearchService } from '../events/event-search.service.js';
import { InterestsService } from '../interests/interests.service.js';
import { PeopleService } from '../profiles/people.service.js';
import { GamificationService } from './gamification.service.js';

export const RECAP_READY_EVENT = 'recap.ready';
const TOP_PEOPLE = 3;

type RecapRow = typeof recaps.$inferSelect;
/** What is stored: people as ids (photo links expire; blocks made later must apply). */
type StoredStats = Omit<RecapStats, 'topPeople'> & { topPeopleIds: string[] };

/** Most frequent value; ties go to the first one seen (stable). */
export function mostFrequent(values: string[]): string | null {
  const counts = new Map<string, number>();
  for (const v of values) counts.set(v, (counts.get(v) ?? 0) + 1);
  let best: string | null = null;
  let bestN = 0;
  for (const [v, n] of counts)
    if (n > bestN) {
      best = v;
      bestN = n;
    }
  return best;
}

/** Monthly and yearly recaps (F-GAM-04): generated by the worker for everyone who went out, then pushed. */
@Injectable()
export class RecapsService {
  private readonly logger = new Logger(RecapsService.name);

  constructor(
    @Inject(DB) private readonly db: Database,
    private readonly outbox: OutboxService,
    private readonly gamification: GamificationService,
    private readonly search: EventSearchService,
    private readonly people: PeopleService,
    private readonly cities: CitiesService,
    private readonly interests: InterestsService,
  ) {}

  private async toDtos(userId: string, rows: RecapRow[]): Promise<Recap[]> {
    const stored = rows.map((r) => r.stats as StoredStats);
    const cards = await this.people.cards(
      userId,
      stored.flatMap((s) => s.topPeopleIds),
    );
    return rows.map((r, i) => {
      const { topPeopleIds, ...rest } = stored[i] as StoredStats;
      return {
        id: r.id,
        period: r.period,
        key: r.key,
        stats: {
          ...rest,
          topPeople: topPeopleIds.flatMap((id) => {
            const c = cards.get(id);
            return c ? [c] : [];
          }),
        },
        createdAt: r.createdAt.toISOString(),
      };
    });
  }

  async list(userId: string): Promise<Recap[]> {
    const rows = await this.db
      .select()
      .from(recaps)
      .where(eq(recaps.userId, userId))
      .orderBy(desc(recaps.createdAt))
      .limit(36);
    return this.toDtos(userId, rows);
  }

  async get(userId: string, id: string): Promise<Recap> {
    const [r] = await this.db
      .select()
      .from(recaps)
      .where(and(eq(recaps.id, id), eq(recaps.userId, userId)));
    if (!r) throw AppError.notFound('Recap');
    const [dto] = await this.toDtos(userId, [r]);
    if (!dto) throw AppError.notFound('Recap');
    return dto;
  }

  async stats(userId: string, period: RecapPeriod, key: string): Promise<StoredStats> {
    const { from, to } = recapWindow(period, key);
    const facts = await this.gamification.facts(userId, {
      kinds: ['check_in', 'hosted'],
      from,
      to,
    });
    const checkIns = facts.filter((f) => f.kind === 'check_in');
    const met = new Map<string, number>();
    for (const c of checkIns) {
      for (const other of await this.search.checkedInAndHosts(c.ref))
        if (other !== userId) met.set(other, (met.get(other) ?? 0) + 1);
    }
    const neighbourhoodIds = [
      ...new Set(
        checkIns.flatMap((c) =>
          typeof c.attrs.neighbourhoodId === 'string' ? [c.attrs.neighbourhoodId] : [],
        ),
      ),
    ];
    const vibes = checkIns.flatMap((c) => {
      const v = (c.attrs as Record<string, unknown>).vibeTagIds;
      return Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string') : [];
    });
    const topVibeId = mostFrequent(vibes);
    const topIds = [...met.entries()]
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
      .map(([id]) => id);
    const [names, vibeTags, cards, longestStreak, earned] = await Promise.all([
      this.cities.neighbourhoodNames(neighbourhoodIds),
      topVibeId ? this.interests.vibeTagsByIds([topVibeId]) : Promise.resolve([]),
      this.people.cards(userId, topIds.slice(0, TOP_PEOPLE * 3)),
      this.gamification.longestStreakBetween(userId, from, to),
      this.gamification.earnedBetween(userId, from, to),
    ]);
    return {
      eventsAttended: checkIns.length,
      eventsHosted: facts.filter((f) => f.kind === 'hosted').length,
      peopleMet: met.size,
      neighbourhoods: neighbourhoodIds.flatMap((id) => {
        const n = names.get(id);
        return n ? [n] : [];
      }),
      topVibe: vibeTags[0] ? LocalizedText.parse(vibeTags[0].name) : null,
      longestStreak,
      badges: earned,
      // Only people who are still active and visible to them right now.
      topPeopleIds: topIds.filter((id) => cards.has(id)).slice(0, TOP_PEOPLE),
    };
  }

  /** Creates the recap for everyone who checked in during the period (idempotent per person and period). */
  async generate(period: RecapPeriod, key: string): Promise<number> {
    const { from, to } = recapWindow(period, key);
    const res = await this.db
      .selectDistinct({ userId: gamificationFacts.userId })
      .from(gamificationFacts)
      .where(
        and(
          eq(gamificationFacts.kind, 'check_in'),
          gte(gamificationFacts.at, from),
          lt(gamificationFacts.at, to),
          sql`NOT EXISTS (SELECT 1 FROM recaps r WHERE r.user_id = ${gamificationFacts.userId} AND r.period = ${period} AND r.key = ${key})`,
        ),
      );
    let created = 0;
    for (const { userId } of res) {
      try {
        const stats = await this.stats(userId, period, key);
        const id = uuidv7();
        const inserted = await this.db.transaction(async (tx) => {
          const rows = await tx
            .insert(recaps)
            .values({ id, userId, period, key, stats })
            .onConflictDoNothing()
            .returning({ id: recaps.id });
          if (rows.length === 0) return false;
          await this.outbox.add(tx, {
            aggregateType: 'user',
            aggregateId: userId,
            type: RECAP_READY_EVENT,
            payload: { recapId: id, userId, period, key },
          });
          return true;
        });
        if (inserted) created += 1;
      } catch (err) {
        this.logger.warn(`Recap ${period} ${key} for ${userId} failed: ${String(err)}`);
      }
    }
    return created;
  }

  /** 1st of the month: last month's recaps; on 1 January also last year's. */
  async generateDue(now: Date = new Date()): Promise<number> {
    let n = await this.generate('month', previousRecapKey('month', now));
    const ist = new Date(now.getTime() + 330 * 60_000);
    if (ist.getUTCMonth() === 0) n += await this.generate('year', previousRecapKey('year', now));
    return n;
  }

  async markNotified(id: string, now: Date = new Date()): Promise<void> {
    await this.db.update(recaps).set({ notifiedAt: now }).where(eq(recaps.id, id));
  }

  async exportFor(userId: string): Promise<Record<string, unknown>> {
    return { recaps: await this.list(userId) };
  }

  async eraseFor(userId: string, tx: Tx): Promise<void> {
    await tx.delete(recaps).where(eq(recaps.userId, userId));
  }
}
