/** Deterministic seed persona #i (no randomness, so seeds are reproducible). */
export function seedPersona(i: number): {
  phone: string;
  displayName: string;
  dob: string;
  gender: 'woman' | 'man' | 'non_binary';
} {
  const first = FIRST[i % FIRST.length] ?? 'Sam';
  const last = LAST[Math.floor(i / FIRST.length) % LAST.length] ?? 'Rao';
  const year = 1988 + (i % 17);
  const month = String((i % 12) + 1).padStart(2, '0');
  const day = String((i % 27) + 1).padStart(2, '0');
  const gender = i % 13 === 0 ? 'non_binary' : i % 2 === 0 ? 'man' : 'woman';
  return {
    phone: `+9190000${String(10000 + i).padStart(5, '0')}`,
    displayName: `${first} ${last.charAt(0)}.`,
    dob: `${year}-${month}-${day}`,
    gender,
  };
}
