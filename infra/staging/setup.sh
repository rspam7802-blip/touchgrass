#!/usr/bin/env bash
# Creates infra/staging/.env for a test server: public addresses, strong random secrets, test mode.
# Usage: ./setup.sh <server public IP> <your email> "+91XXXXXXXXXX:123456,+91YYYYYYYYYY:654321"
set -euo pipefail
cd "$(dirname "$0")"

usage() {
  echo 'Usage: ./setup.sh <server public IP> <your email> "+91XXXXXXXXXX:123456,+91YYYYYYYYYY:654321"' >&2
  exit 1
}
[[ $# -eq 3 ]] || usage
IP="$1"
EMAIL="$2"
LOGINS="$3"
if ! [[ "$LOGINS" =~ ^\+[1-9][0-9]{7,14}:[0-9]{6}(,\+[1-9][0-9]{7,14}:[0-9]{6})*$ ]]; then
  echo 'Tester logins must look like "+919876543210:482913,+919812345678:730164"' >&2
  exit 1
fi

if [[ -f .env ]]; then
  echo ".env already exists; delete it first if you really want new secrets (existing data uses the old ones)." >&2
  exit 1
fi
if ! [[ "$IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then echo "Not an IPv4 address: $IP" >&2; exit 1; fi

BASE="${IP//./-}.sslip.io"
secret() { openssl rand -hex 32; }
PG_PASS="$(openssl rand -hex 16)"
S3_KEY="tg$(openssl rand -hex 8)"
S3_SECRET="$(secret)"

umask 077
cat > .env <<ENV
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep this file private (it holds the secrets).
BASE_HOST=${BASE}
ACME_EMAIL=${EMAIL}

# Test mode: fake SMS/payments/maps are allowed outside "production". The 000000 shortcut is OFF;
# only the numbers in TEST_LOGINS can sign in (with their own codes). Others' codes appear in the API log.
NODE_ENV=development
OTP_DEV_BYPASS=false
TEST_LOGINS=${LOGINS}
APP_VERSION=0.1.0
LOG_LEVEL=info

API_PORT=4000
API_WORKERS=1
REALTIME_PORT=4001
API_PUBLIC_URL=https://api.${BASE}
WEB_PUBLIC_URL=https://app.${BASE}
CORS_ORIGINS=https://app.${BASE}
TRUST_PROXY_HOPS=1

POSTGRES_PASSWORD=${PG_PASS}
DATABASE_URL=postgres://touchgrass:${PG_PASS}@postgres:5432/touchgrass
DATABASE_POOL_MAX=10
REDIS_URL=redis://redis:6379

JWT_ACCESS_SECRET=$(secret)
TOKEN_HASH_PEPPER=$(secret)
SIGNED_URL_SECRET=$(secret)

MIN_SUPPORTED_APP_VERSION=0.1.0
LATEST_APP_VERSION=0.1.0

SMS_PROVIDER=fake
PAYMENTS_PROVIDER=fake
PAYMENTS_FAKE_AUTO_SETTLE=true
PUSH_PROVIDER=fake
MAPS_PROVIDER=fake
WEATHER_PROVIDER=fake
MODERATION_PROVIDER=fake
ANALYTICS_PROVIDER=noop

STORAGE_PROVIDER=s3
S3_ENDPOINT=https://media.${BASE}
S3_REGION=ap-south-1
S3_ACCESS_KEY_ID=${S3_KEY}
S3_SECRET_ACCESS_KEY=${S3_SECRET}
S3_FORCE_PATH_STYLE=true
S3_BUCKET_MEDIA=touchgrass-media
MEDIA_PUBLIC_BASE_URL=https://media.${BASE}/touchgrass-media

EMAIL_PROVIDER=smtp
SMTP_URL=smtp://mailpit:1025
EMAIL_FROM=TouchGrass <hello@touchgrass.app>
ENV

echo "Created infra/staging/.env"
echo
echo "Your test server addresses:"
echo "  API       https://api.${BASE}"
echo "  Realtime  https://rt.${BASE}"
echo "  Website   https://app.${BASE}   (admin console: /admin)"
echo "  Media     https://media.${BASE}"
